#[test]
fn estimate_counts_digits_and_dense_runs_apart() {
    // Prose and code: about 3 characters per token.
    assert_eq!(estimate_tokens("fix the parser"), 5);
    assert_eq!(estimate_tokens(""), 0);
    // Every digit is a token of its own.
    assert_eq!(estimate_tokens("v1.2.3"), 3 + 1);
    // A hash: 40 digits, 24 letters at 2 per token.
    let sha = "141eb93384ad59f77eba3a21bde871851c766de891f778c5686218c214c48f11";
    let digits = sha.chars().filter(char::is_ascii_digit).count();
    assert_eq!(estimate_tokens(sha), digits + (64 - digits).div_ceil(2));
    assert!(estimate_tokens(sha) > sha.len().div_ceil(CHARS_PER_TOKEN) * 3 / 2);
    // A long word without digits is not dense.
    let word = "configurationvaluesbuilder";
    assert_eq!(estimate_tokens(word), word.len().div_ceil(3));
    // Short runs mixing letters and digits are not dense either.
    assert_eq!(estimate_tokens("abc123"), 3 + 1);
}

fn file(path: &str, hunks: &str) -> FileDiff {
    let added = hunks.lines().filter(|l| l.starts_with('+')).count();
    let deleted = hunks.lines().filter(|l| l.starts_with('-')).count();
    FileDiff {
        path: path.to_owned(),
        old_path: None,
        lines: Some((added, deleted)),
        hunks: hunks.to_owned(),
    }
}

#[test]
fn machine_written_needs_strong_evidence() {
    let none: &[String] = &[];
    // Known lockfiles, by name or by the `.lock` extension.
    assert!(machine_written(
        &file("Cargo.lock", "@@ -0,0 +1 @@\n+x\n"),
        none
    ));
    assert!(machine_written(
        &file("web/deno.lock", "@@ -1 +1 @@\n-a\n+b\n"),
        none
    ));
    // A generator's marker at the top of the new file.
    let go =
        "@@ -0,0 +1,3 @@\n+// Code generated by protoc-gen-go. DO NOT EDIT.\n+\n+package api\n";
    assert!(machine_written(&file("api/user.pb.go", go), none));
    let schema = "@@ -1,2 +1,2 @@\n # @generated by sqlc\n-a\n+b\n";
    assert!(machine_written(&file("db/query.sql", schema), none));
    // ... but not deep in the file, nor on a removed line.
    let deep = "@@ -40,2 +40,2 @@\n // DO NOT EDIT this block by hand\n-a\n+b\n";
    assert!(!machine_written(&file("src/config.rs", deep), none));
    let removed = "@@ -1,2 +1,1 @@\n-// @generated\n x\n";
    assert!(!machine_written(&file("src/lib.rs", removed), none));
    // `.gitattributes` says so.
    let marked = vec!["src/schema.ts".to_owned()];
    assert!(machine_written(
        &file("src/schema.ts", "@@ -1 +1 @@\n-a\n+b\n"),
        &marked
    ));
    // Guesses from directories are not enough, nor unknown lockfiles.
    assert!(!machine_written(
        &file("build/main.rs", "@@ -1 +1 @@\n-a\n+b\n"),
        none
    ));
    assert!(!machine_written(
        &file("gradle.lockfile", "@@ -1 +1 @@\n-a\n+b\n"),
        none
    ));
    assert!(!machine_written(&file("src/main.rs", ""), none));
}

fn hunk(lines: usize) -> String {
    let mut text = format!("@@ -1,{lines} +1,{lines} @@\n");
    for n in 0..lines {
        let _ = writeln!(text, "+line {n} of a fairly ordinary change");
    }
    text
}

#[test]
fn parses_numstat_with_renames_and_binaries() {
    let out = "3\t1\tsrc/lib.rs\0-\t-\tlogo.png\0\
               0\t0\t\0old name.rs\0new name.rs\0";
    let files = parse_numstat_z(out);
    assert_eq!(files.len(), 3);
    assert_eq!(files[0].lines, Some((3, 1)));
    assert_eq!(files[1].lines, None);
    assert_eq!(files[2].path, "new name.rs");
    assert_eq!(files[2].old_path.as_deref(), Some("old name.rs"));
}

#[test]
fn pairs_patch_sections_with_numstat_by_order() {
    let patch = "diff --git a/a.rs b/a.rs\nindex 1..2 100644\n--- a/a.rs\n+++ b/a.rs\n\
                 @@ -1 +1 @@\n-old\n+new\n\
                 diff --git a/logo.png b/logo.png\nBinary files differ\n";
    let files = parse("1\t1\ta.rs\0-\t-\tlogo.png\0", patch);
    assert_eq!(files[0].hunks, "@@ -1 +1 @@\n-old\n+new\n");
    assert_eq!(files[1].hunks, "");
}

#[test]
fn conflict_sections_are_split_too() {
    let patch = "diff --cc both.rs\nindex 1,2..3\n@@@ -1,1 -1,1 +1,1 @@@\n- a\n -b\n++c\n\
                 diff --git a/x.rs b/x.rs\n@@ -1 +1 @@\n-x\n+y\n";
    let files = parse("1\t1\tboth.rs\x001\t1\tx.rs\0", patch);
    assert!(files[0].hunks.starts_with("@@@"));
    assert_eq!(files[1].hunks, "@@ -1 +1 @@\n-x\n+y\n");
}

#[test]
fn lines_starting_with_diff_inside_hunks_do_not_split() {
    // A removed line `-diff --git` starts with `-`, not `diff`.
    let patch = "diff --git a/a.md b/a.md\n@@ -1 +1 @@\n-diff --git x\n+ok\n";
    let files = parse("1\t1\ta.md\0", patch);
    assert!(files[0].hunks.ends_with("-diff --git x\n+ok\n"));
}

#[test]
fn last_stat_line_needs_no_room_for_the_summary() {
    let files = [file("a.rs", ""), file("b.rs", "")];
    let exact = estimate_tokens(&stat_line(&files[0])) + estimate_tokens(&stat_line(&files[1]));
    assert_eq!(render_stat(&files, exact), "a.rs | +0 -0\nb.rs | +0 -0\n");
    // One token short: a line plus the summary would not fit either.
    assert_eq!(render_stat(&files, exact - 1), "... and 2 more files\n");
}

